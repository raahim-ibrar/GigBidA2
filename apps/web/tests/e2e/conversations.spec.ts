import { test, expect } from "@playwright/test";

test.skip(!process.env.GIGBID_TEST_DATABASE_URL, "Requires disposable Postgres schema and deterministic worker fixtures");
test.setTimeout(60000);

test("review, edit and save replies across client messages and reloads", async ({ page }) => {
  await page.goto("/sign-in");
  await page.getByRole("button", { name: "Create a new account" }).click();
  await page.getByLabel("Email", { exact: true }).fill(`conversation-${crypto.randomUUID()}@example.org`);
  await page.getByLabel("Password", { exact: true }).fill("Browser conversation fixture password 123!");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Set up your profile" })).toBeVisible();
  await page.goto("/portfolio");
  await page.getByLabel("Portfolio file").setInputFiles({ name: "reply-fixture.md", mimeType: "text/markdown", buffer: Buffer.from("I built a Python API.") });
  await page.getByLabel("Project or portfolio title").fill("Conversation browser fixture");
  await page.getByRole("button", { name: "Upload evidence" }).click();
  await expect(page.getByTestId("source-status")).toHaveText("ready");
  await page.goto("/inbox");
  await page.getByLabel("Job title", { exact: true }).fill("Conversation API fixture");
  await page.getByLabel("Job description and screening questions").fill("Build a Python API.");
  await page.getByLabel("Maximum client budget").fill("30");
  await page.getByRole("button", { name: "Analyse and draft" }).click();
  await expect(page.getByRole("heading", { name: "Verified draft for review" })).toBeVisible({ timeout: 30000 });
  await page.goto("/messages");
  await page.getByLabel("Conversation title").fill("API client discussion");
  await page.getByLabel("Client message", { exact: true }).fill("Tell me about your experience.");
  await page.getByRole("button", { name: "Draft a reply", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Verified reply for review" })).toBeVisible({ timeout: 20000 });
  await page.getByLabel("Edit reply").fill("Could we discuss scope?");
  await page.getByRole("button", { name: "Verify edits and request a new review" }).click();
  await expect(page.getByLabel("Edit reply")).toHaveValue("Could we discuss scope?", { timeout: 15000 });
  await page.getByRole("button", { name: "Approve and save email draft" }).click();
  await expect(page.getByRole("heading", { name: "Saved local email draft" })).toBeVisible({ timeout: 15000 });
  await page.reload();
  await expect(page.getByRole("heading", { name: "Saved local email draft" })).toBeVisible();
  await page.getByLabel("New client message").fill("Can we clarify the scope?");
  await page.getByRole("button", { name: "Add message and draft reply" }).click();
  await expect(page.getByRole("heading", { name: "Verified reply for review" })).toBeVisible({ timeout: 15000 });
  await expect(page.getByRole("heading", { name: "Saved local email draft" })).toHaveCount(0);
  await page.getByRole("button", { name: "Approve and save email draft" }).click();
  await expect(page.getByRole("heading", { name: "Saved local email draft" })).toBeVisible({ timeout: 15000 });
  await page.reload();
  const drafts = page.getByRole("heading", { name: "Approved local email drafts" }).locator("..");
  await expect(drafts.locator("article")).toHaveCount(2);
});
