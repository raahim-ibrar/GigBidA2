"""Generate Mermaid directly from the compiled graph topology without executing nodes."""

import argparse
from pathlib import Path

from langgraph.checkpoint.memory import InMemorySaver

from agent.graphs.bid_graph import build_bid_graph
from agent.graphs.conversation_graph import build_conversation_graph

ROOT = Path(__file__).resolve().parents[1]


def artifacts():
    graphs = {
        "bid": build_bid_graph(checkpointer=InMemorySaver()),
        "conversation": build_conversation_graph(checkpointer=InMemorySaver()),
    }
    diagrams = {name: graph.get_graph().draw_mermaid() for name, graph in graphs.items()}
    page = "# Graphs generated from code\n\n"
    page += "Generated by `python scripts/render_graphs.py`. No business node is executed. "
    page += (
        "The in-memory saver is used only for topology inspection; production uses Postgres.\n\n"
    )
    for name, diagram in diagrams.items():
        page += f"## {name.title()} graph\n\n```mermaid\n{diagram}\n```\n\n"
    result = {ROOT / "docs/GRAPHS.md": page}
    result.update(
        {
            ROOT / f"docs/images/{name}_graph.mmd": diagram + "\n"
            for name, diagram in diagrams.items()
        }
    )
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                parser.exit(1, f"Graph diagram is stale: {path.relative_to(ROOT)}\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print("Compiled graph diagrams are current.")


if __name__ == "__main__":
    main()
